// Гарантия маршрута к администратору.
//
// Если ответа в базе знаний нет, студента нужно направить к администраторам —
// кнопка «👨‍💼 Передать администратору» под ответом ИИ. Промпт этого требует, но модель
// слушается не всегда: вместо кнопки советует «загляните на сайт» или
// «напишите в техподдержку». Поэтому маршрут дописывается в коде, а не
// остаётся на усмотрение модели.

const ADMIN_LINE = 'Если нужен точный ответ — нажмите «👨‍💼 Передать администратору», администратор ответит лично.';
const REFUSAL = 'Я могу помочь только по вопросам, связанным с университетом';

// Модель уже упомянула администратора — дописывать не нужно
const MENTIONS_ADMIN = /передать\s+админ|администратор/i;

// Модель сама признаёт, что ответа нет
// (оба порядка слов: «нет в базе знаний» и «в базе знаний нет»)
const ADMITS_MISSING = /нет\s+в\s+(?:нашей\s+|доступной\s+)?базе|в\s+(?:нашей\s+|доступной\s+)?базе(?:\s+знаний)?\s+(?:этого\s+|такой\s+информации\s+)?нет|отсутству|не\s+содерж\w*\s+информаци|не\s+могу\s+(?:предоставить|подсказать|сообщить|ответить)|нет\s+(?:точной\s+|актуальной\s+|подробной\s+|официальной\s+)?(?:информации|данных|сведений)/i;

/**
 * @param {string} text ответ модели (уже после fact_guard)
 * @param {{ hadContext: boolean }} opts был ли у модели контекст из базы знаний
 */
function ensureAdminRoute(text, { hadContext }) {
    // Отказ на посторонний запрос — администратор тут не поможет
    if (text.includes(REFUSAL)) return text;
    if (MENTIONS_ADMIN.test(text)) return text;

    // Без контекста у модели не было проверенных фактов — любой такой ответ
    // неполный. С контекстом дописываем, только если модель сама признала,
    // что нужного в нём нет.
    if (!hadContext || ADMITS_MISSING.test(text)) {
        return `${text.trim()}\n\n${ADMIN_LINE}`;
    }
    return text;
}

module.exports = { ensureAdminRoute, ADMIN_LINE };
